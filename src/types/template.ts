import { relative } from 'node:path'

/** Options used to generate the Nuxt configuration type declarations. */
export interface CreateConfigTypesOptions {
  buildDir: string
  configTypeFile?: string
  runtimeConfigKeys?: readonly string[]
}

/**
 * Generates Nuxt and Nitro type declarations from the explicit contract or loaded layers.
 *
 * @param configFiles Configuration file paths contributing to the resolved configuration.
 * @param options Type generation options.
 * @param options.buildDir Nuxt generated build directory.
 * @param options.configTypeFile File exporting the explicit environment configuration type.
 * @param options.runtimeConfigKeys Runtime fields supplied by this module.
 * @returns Generated TypeScript module augmentation content.
 */
export const createConfigTypes = (
  configFiles: string | string[],
  {
    buildDir,
    configTypeFile,
    runtimeConfigKeys = [],
  }: CreateConfigTypesOptions,
) => {
  const importPath = (configFile: string) => {
    let configImport = relative(buildDir, configFile)
      .replaceAll('\\', '/')
      .replace(/\.[cm]?tsx?$/, '')

    if (!configImport.startsWith('.')) configImport = `./${configImport}`
    return JSON.stringify(configImport)
  }
  const configTypeImport = configTypeFile
    ? `import type { NuxtConfEnvConfig } from ${importPath(configTypeFile)}
import type { NuxtConfKnownFields } from 'nuxt-conf/core'`
    : 'import type { NuxtConfMerge } from \'nuxt-conf/core\''
  const resolvedConfigType = configTypeFile
    ? 'NuxtConfKnownFields<NuxtConfEnvConfig>'
    : (Array.isArray(configFiles) ? configFiles : [configFiles]).reduce(
        (high, file) => `NuxtConfMerge<${high}, typeof import(${importPath(file)}).default>`,
        'Record<never, never>',
      )

  const runtimeKeys = runtimeConfigKeys.map(key => JSON.stringify(key)).join(' | ') || 'never'
  const runtimeConfigTypes = runtimeConfigKeys.length
    ? `  interface RuntimeConfig extends NuxtConfRuntimeConfig {}\n`
    : ''
  const nitroRuntimeConfigTypes = runtimeConfigKeys.length
    ? `declare module 'nitropack/types' {
  interface NitroRuntimeConfig extends NuxtConfRuntimeConfig {}
}`
    : ''
  const schemaTypes = `${runtimeConfigTypes}  interface CustomAppConfig extends NuxtConfPublicConfig, NuxtConfBuildFields {}`

  return `// Generated by nuxt-conf. Do not edit manually.

${configTypeImport}

type NuxtConfResolvedConfig = ${resolvedConfigType}

type NuxtConfPublicConfig = Omit<{
  [K in keyof NuxtConfResolvedConfig as
    [Extract<NuxtConfResolvedConfig[K], { private: true }>] extends [never] ? K : never
  ]: NuxtConfResolvedConfig[K]
}, keyof NuxtConfBuildFields>

type NuxtConfBuildFields = {
  NUXT_APP_CDN_URL?: string
  NUXT_APP_CDN_VERSION?: string
  NUXT_APP_CDN_BASE_URL?: string
  NUXT_APP_SENTRY_RELEASE?: string
}

type NuxtConfRuntimeFields = Omit<NuxtConfResolvedConfig, keyof NuxtConfBuildFields> & NuxtConfBuildFields
type NuxtConfRuntimeConfig = Required<Pick<NuxtConfRuntimeFields, Extract<keyof NuxtConfRuntimeFields, ${runtimeKeys}>>>

declare module 'nuxt/schema' {
${schemaTypes}
}

declare module '@nuxt/schema' {
${schemaTypes}
}

${nitroRuntimeConfigTypes}

export {}
`
}
