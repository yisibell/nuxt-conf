import { relative } from 'node:path'

export const createConfigTypes = (
  configFile: string,
  buildDir: string,
  injectRuntimeConfig = true,
) => {
  let configImport = relative(buildDir, configFile)
    .replaceAll('\\', '/')
    .replace(/\.[cm]?tsx?$/, '')

  if (!configImport.startsWith('.')) {
    configImport = `./${configImport}`
  }

  const runtimeConfigTypes = `${injectRuntimeConfig
    ? `  interface RuntimeConfig extends NuxtConfResolvedConfig {
    NUXT_APP_CDN_URL?: string
    NUXT_APP_CDN_VERSION?: string
    NUXT_APP_CDN_BASE_URL?: string
  }`
    : ''}
  interface AppConfig extends NuxtConfPublicConfig {
    NUXT_APP_CDN_URL?: string
    NUXT_APP_CDN_VERSION?: string
    NUXT_APP_CDN_BASE_URL?: string
  }`

  return `// Generated by nuxt-conf. Do not edit manually.
type NuxtConfResolvedConfig = typeof import(${JSON.stringify(configImport)}).default
type NuxtConfPublicConfig = {
  [K in keyof NuxtConfResolvedConfig as
    NuxtConfResolvedConfig[K] extends { private: true } ? never : K
  ]: NuxtConfResolvedConfig[K]
}

declare module 'nuxt/schema' {
${runtimeConfigTypes}
}

declare module '@nuxt/schema' {
${runtimeConfigTypes}
}

export {}
`
}
