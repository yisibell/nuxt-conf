import { relative } from 'node:path'

/** Options used to generate the Nuxt configuration type declarations. */
export interface CreateConfigTypesOptions {
  buildDir: string
  injectRuntimeConfig?: boolean
}

/**
 * Generates Nuxt and Nitro type declarations for the loaded environment config.
 *
 * @param configFile Selected environment configuration file.
 * @param options Type generation options.
 * @param options.buildDir Nuxt generated build directory.
 * @param options.injectRuntimeConfig Whether the loaded config is injected into runtime config.
 * @returns Generated TypeScript module augmentation content.
 */
export const createConfigTypes = (
  configFile: string,
  {
    buildDir,
    injectRuntimeConfig = true,
  }: CreateConfigTypesOptions,
) => {
  let configImport = relative(buildDir, configFile)
    .replaceAll('\\', '/')
    .replace(/\.[cm]?tsx?$/, '')

  if (!configImport.startsWith('.')) {
    configImport = `./${configImport}`
  }

  const runtimeConfigFields = [
    '    NUXT_APP_SENTRY_RELEASE?: string',
    ...(injectRuntimeConfig
      ? [
          '    NUXT_APP_CDN_URL?: string',
          '    NUXT_APP_CDN_VERSION?: string',
          '    NUXT_APP_CDN_BASE_URL?: string',
        ]
      : []),
  ].join('\n')

  const runtimeConfigTypes = `  interface RuntimeConfig extends NuxtConfPublicConfig {
${runtimeConfigFields}
  }

  interface AppConfig extends NuxtConfPublicConfig {
    NUXT_APP_CDN_URL?: string
    NUXT_APP_CDN_VERSION?: string
    NUXT_APP_CDN_BASE_URL?: string
    NUXT_APP_SENTRY_RELEASE?: string
  }`

  const nitroRuntimeConfigTypes = injectRuntimeConfig
    ? `declare module 'nitropack/types' {
  interface NitroRuntimeConfig extends NuxtConfPrivateConfig {}
}`
    : ''

  return `// Generated by nuxt-conf. Do not edit manually.

type NuxtConfResolvedConfig = typeof import(${JSON.stringify(configImport)}).default

type NuxtConfPublicConfig = {
  [K in keyof NuxtConfResolvedConfig as
    NuxtConfResolvedConfig[K] extends { private: true } ? never : K
  ]: NuxtConfResolvedConfig[K]
}

type NuxtConfPrivateConfig = {
  [K in keyof NuxtConfResolvedConfig as
    NuxtConfResolvedConfig[K] extends { private: true } ? K : never
  ]: NuxtConfResolvedConfig[K]
}

declare module 'nuxt/schema' {
${runtimeConfigTypes}
}

declare module '@nuxt/schema' {
${runtimeConfigTypes}
}

${nitroRuntimeConfigTypes}

export {}
`
}
